"""
@file check-journal-pdf.py
@input Paths to PDFs generated by test-journal-pdf-renderer.mjs
@output Searchability/bounds checks, page PNGs and contact sheets beside the PDFs
@pos Test runner (requires PyMuPDF and Pillow)
@updated 2026-10-23: Verifies dual fonts, paragraph baselines, nonduplicated notes and actual calendar content.
@updated 2026-10-23: Verifies mixed orientation, even facing spreads, original stickers and nested book order.
@updated 2026-10-23: Requires every A4 page to be landscape and every A5 page to be portrait.
@updated 2026-10-23: Checks independent covers, direct check counts, compact columns and six donut dimensions.
@updated 2026-10-23: Checks English headings, four readable type tiers, half-pixel rules and complete rich Logs.
@updated 2026-10-24: Checks branded covers, shared badge names, nested year/month/week statistics and a single spread axis.
@updated 2026-10-24: Verifies a daily-page-only export keeps every daily section and excludes other page groups.
@updated 2026-10-24: Confirms guidance and AI narrative use separate peer headings without empty guidance on narrative-only days.
@updated 2026-10-24: Checks all 1100 dates/summaries, final page numbering and A4/A5 geometry in large-book downloads.
@updated 2026-10-24: Checks rendered narrative heading levels, single-copy bold text, list content and working Markdown links.
@updated 2026-10-24: Reopens the 96-page simulated native save and checks the uploaded font and every daily summary.
"""
from pathlib import Path
from datetime import date, timedelta
import json
import re
import sys

import fitz
from PIL import Image, ImageDraw, ImageFont


def inspect_daily_review_sections(document):
    days = {
        date: [page for page in document if next(iter(page.get_text().splitlines()), '').startswith(date)]
        for date in ['2026-08-03', '2026-08-04']
    }
    rich = '\n'.join(page.get_text() for page in days['2026-08-03'])
    narrative_only = '\n'.join(page.get_text() for page in days['2026-08-04'])
    assert '\n引导\n' in rich and '\n叙事\n' in rich, 'Daily guidance and AI narrative are not separate headings'
    assert rich.index('\n引导\n') < rich.index('\n叙事\n'), 'Narrative is not after the complete guidance section'
    assert '八月的第三天' in rich.replace('\n', ''), 'AI narrative was lost'
    assert '\n叙事\n' in narrative_only and '\n引导\n' not in narrative_only, 'Narrative-only day has missing narrative or empty guidance'
    headings = [span for page in days['2026-08-03'] for block in page.get_text('dict')['blocks'] for line in block.get('lines', []) for span in line['spans'] if span['text'] in ['引导', '叙事']]
    assert len(headings) == 2 and all(abs(span['size'] - 12) < 0.01 for span in headings), 'Guidance and narrative are not peer headings'
    visible = rich.replace('\n', '')
    assert visible.count('专心阅读的时光') == 1, 'Bold narrative text was lost or duplicated'
    for value in ['留下一张手写的书签', '记下今天的收获', '明天继续阅读', '三十页', '半小时', '把日子慢慢写下来。']:
        assert value in visible, f'Markdown content missing: {value}'
    assert '**' not in rich and '```' not in rich and '[x]' not in rich, 'Narrative Markdown markers were printed literally'
    spans = [span for page in days['2026-08-03'] for block in page.get_text('dict')['blocks'] for line in block.get('lines', []) for span in line['spans']]
    for title, size in [('八月的第三天', 12), ('值得留住的片刻', 12), ('生活的小事', 9), ('一点调整', 9), ('留给明天', 9), ('随手记', 9)]:
        assert any(span['text'] == title and abs(span['size'] - size) < 0.01 for span in spans), f'Markdown heading not styled: {title}'
    stroked = ''.join(''.join(chr(char[0]) for char in trace['chars']) for page in days['2026-08-03'] for trace in page.get_texttrace() if trace['type'] == 1)
    assert '专心阅读的时光' in stroked, 'Bold text has no stroke emphasis'
    assert all(abs(trace['dir'][1]) < 0.001 for page in days['2026-08-03'] for trace in page.get_texttrace()), 'Italic text rotated its baseline instead of shearing the glyphs'
    assert any(link.get('uri') == 'https://example.com/reading' for page in days['2026-08-03'] for link in page.get_links()), 'Markdown link lost its destination'


def inspect_mood_year(source):
    document = fitz.open(source)
    overview = [page for page in document if 'Mood Overview' in next(iter(page.get_text().splitlines()), '')]
    assert len(overview) == 1, 'Annual mood matrix must fit one page'
    page = overview[0]
    images = page.get_image_info()
    assert len(images) == 365, f'Expected 365 mood stickers, got {len(images)}'
    if source.stem.endswith('a4'):
        assert len(re.findall(r'^\d{2} / [A-Z]{3}$', page.get_text(), re.MULTILINE)) == 12, 'A4 moods are not twelve mini calendars'
    assert all(image['bbox'][2] - image['bbox'][0] < 15 and image['bbox'][3] - image['bbox'][1] < 15 for image in images), 'Annual stickers are too large'
    summaries = [page for page in document if 'One Line a Day' in next(iter(page.get_text().splitlines()), '')]
    assert len(summaries) == 1, 'Sixteen one-line summaries should fit one compact page'
    output = source.parent / source.stem
    output.mkdir(exist_ok=True)
    page.get_pixmap(matrix=fitz.Matrix(2, 2), alpha=False).save(output / 'annual-mood.png')
    summaries[0].get_pixmap(matrix=fitz.Matrix(2, 2), alpha=False).save(output / 'annual-summaries.png')
    return {'file': str(source), 'pages': len(document), 'mood_stickers': len(images), 'overview': str(output / 'annual-mood.png')}


def inspect(filename):
    source = Path(filename)
    if source.stem == 'journal-native-custom':
        document = fitz.open(source)
        assert len(document) == 96, 'Native chunk save lost PDF pages'
        for index, page in enumerate(list(document)[1:], start=1):
            assert f'第{index}天，使用自定义字体。' in page.get_text().replace('\n', ''), f'Native save lost daily content: {index}'
        assert any('wenkai' in font[3].lower() for page in document for font in page.get_fonts()), 'Uploaded font was replaced'
        assert '96 / 96' in document[-1].get_text(), 'Native save lost its final footer'
        output = source.parent / source.stem
        output.mkdir(exist_ok=True)
        for index in [1, 95]:
            document[index].get_pixmap(matrix=fitz.Matrix(1.4, 1.4), alpha=False).save(output / f'page-{index + 1}.png')
        return {'file': str(source), 'pages': len(document), 'daily_summaries': 95, 'uploaded_font': 'preserved'}
    if source.stem.startswith('journal-large-'):
        document = fitz.open(source)
        assert len(document) > 1100, 'Large journal was truncated'
        daily_pages = []
        for index, page in enumerate(document):
            lines = page.get_text().splitlines()
            match = re.match(r'^(\d{4}-\d{2}-\d{2}) ', lines[0] if lines else '')
            if match:
                daily_pages.append((index, match.group(1)))
                expected = f'第{len(daily_pages)}天的手账记录。'
                assert expected in page.get_text().replace('\n', ''), f'Missing daily summary: {expected}'
            assert abs(page.rect.width - (419.53 if source.stem.endswith('a5') else 841.89)) < 0.1, f'Wrong page width: {index + 1}'
            assert abs(page.rect.height - 595.28) < 0.1, f'Wrong page height: {index + 1}'
        assert [key for _, key in daily_pages] == [(date(2023, 1, 1) + timedelta(days=index)).isoformat() for index in range(1100)], 'Missing or duplicated dates in large journal'
        assert f'{len(document)} / {len(document)}' in document[-1].get_text(), 'Final page number is incomplete'
        output = source.parent / source.stem
        output.mkdir(exist_ok=True)
        for index in [daily_pages[0][0], 1000, len(document) - 1]:
            document[index].get_pixmap(matrix=fitz.Matrix(1.4, 1.4), alpha=False).save(output / f'page-{index + 1}.png')
        return {'file': str(source), 'pages': len(document), 'daily_pages': len(daily_pages), 'last_date': daily_pages[-1][1]}
    if source.stem.startswith('journal-mood-year-'):
        return inspect_mood_year(source)
    if source.stem == 'journal-daily-only':
        document = fitz.open(source)
        inspect_daily_review_sections(document)
        text = ''.join(page.get_text() for page in document).replace('\n', '')
        for value in ['今日计划', '时间线 日志', '日课', '总结', '引导', '#学习与创作', '@产品方案初稿', '%学习成长', '阅读页数', '32 页', '评论']:
            assert value in text, f'Daily page group lost content: {value}'
        for value in ['Monthly Planner', 'Weekly Planner', 'Weekly Timeline', 'Time Distribution', 'Habit Tracker', 'Mood Overview', 'One Line a Day', 'Goals']:
            assert value not in text, f'Unselected page group leaked: {value}'
        assert sum(len(page.get_image_info()) for page in document) > 0, 'Daily group lost photos and stickers'
        assert text.count('把摘录和照片一起留在这里。') == 1, 'Daily group lost or duplicated rich Log comments'
        return {'file': str(source), 'pages': len(document), 'daily_group': 'complete'}
    document = fitz.open(source)
    inspect_daily_review_sections(document)
    text = '\n'.join(page.get_text() for page in document)
    body = '\n'.join(page.get_text() for page in document if 'Weekly Timeline' not in next(iter(page.get_text().splitlines()), ''))
    continuous = text.replace('\n', '')
    assert 'Contents' in text and 'Goals' in text, 'Missing contents/annual data'
    for title in ['Monthly Planner', 'Weekly Planner', '一日一页', 'Weekly Timeline', '日志', 'Habit Tracker', '引导', '每周回顾', 'Time Distribution', 'One Line a Day']:
        assert title in text, f'Missing chapter: {title}'
    assert body.count('把这页书的余味留给明天。') == 1, 'Full log note repeated across chapters or lost'
    assert body.count('关灯前，把它抄在了纸上。') == 1, 'Overnight log note duplicated on the second date'
    assert body.count('周五前发给设计组讨论。') == 1, 'Plan note repeated at schedule/deadline or across chapters'
    assert '2/3' in text, 'Counted check missing'
    assert '计数明细' not in text, 'Counted checks still have a redundant appendix'
    for value in ['阅读页数', '32 页', '小说 / 随笔', '摘录感受', '进度增量', '@产品方案初稿', '%学习成长', '#学习与创作', '夏日阅读', '专注评分', '心情评分', '评论', '旧书', '夏日散步']:
        assert value in continuous, f'Missing rich Log field: {value}'
    assert continuous.count('下次读书会可以从这一章开始。') == 1, 'Comment lost or duplicated'
    assert continuous.count('把摘录和照片一起留在这里。') == 1, 'Comment paragraphs lost or duplicated'
    assert '[[' not in text and 'Connections' not in text, 'Nodes should be styled only inside the note'
    assert '[x]' not in text and '[ ]' not in text, 'Unrendered Markdown checkboxes remain'
    assert 'Statistics' not in text, 'Statistics should be integrated with the bar charts'
    assert any(document.xref_get_key(xref, 'Contents')[1] == '阅读笔记' for page in document for xref, _, _ in page.annot_xrefs()), 'Canonical node target missing'
    assert '\ufffd' not in text, 'Invalid Chinese text extraction'
    assert any(document.extract_font(font[0])[3] for font in document[0].get_fonts()), 'No embedded font'
    titles = []
    issues = []
    spans = []
    calendar_pages = []
    timeline_pages = []
    month_indices = []
    timeline_indices = []
    blank_indices = []
    sticker_pages = []
    output = source.parent / source.stem
    output.mkdir(exist_ok=True)
    for index, page in enumerate(document):
        margin = 28 if 'a5' in source.stem else 40
        lines = page.get_text().splitlines()
        titles.append({'page': index + 1, 'title': lines[0] if lines else ''})
        if 'Monthly Planner' in (lines[0] if lines else ''):
            calendar_pages.append(page.get_text())
            month_indices.append(index)
        if 'Weekly Timeline' in (lines[0] if lines else ''):
            timeline_pages.append(page)
            timeline_indices.append(index)
        expected_width = 419.53 if 'a5' in source.stem else 841.89
        assert abs(page.rect.width - expected_width) < 0.1, f'Wrong page orientation on {index + 1}'
        assert abs(page.rect.height - 595.28) < 0.1, f'Wrong page height on {index + 1}'
        for picture in page.get_image_info():
            bounds = picture['bbox']
            assert abs((bounds[2] - bounds[0]) / (bounds[3] - bounds[1]) - picture['width'] / picture['height']) < 0.02, f'Distorted image on page {index + 1}'
        for drawing in page.get_drawings():
            if drawing.get('color') and drawing.get('width', 0) > 0:
                assert abs(drawing['width'] - 0.375) < 0.01, f'Unexpected border width on page {index + 1}'
        if any(image[2] > 200 and image[3] > 200 for image in page.get_images()) and '总结' in page.get_text():
            sticker_pages.append(index)
        for block in page.get_text('dict')['blocks']:
            for line in block.get('lines', []):
                for span in line['spans']:
                    spans.append({**span, 'page': index + 1})
                    x0, y0, x1, y1 = span['bbox']
                    if x0 < margin - 1 or x1 > page.rect.width - margin + 2 or y1 > page.rect.height - margin + 13:
                        issues.append({'page': index + 1, 'text': span['text'][:70], 'bbox': span['bbox']})
        pixmap = page.get_pixmap(matrix=fitz.Matrix(1.4, 1.4), alpha=False)
        # Extraction succeeds even with a broken WOFF2 subset; verify visible ink in the title itself.
        title_area = fitz.Rect(margin, margin, page.rect.width - margin, margin + 32)
        if index == 0 and 'Life Journal' in page.get_text():
            assert 'Life Journal' in page.get_text(), 'Cover title missing'
            assert 'LUMOSTIME   /   JOURNAL' not in page.get_text(), 'Cover still uses body header'
            title_area = page.search_for('Life Journal')[0]
        title = page.get_pixmap(matrix=fitz.Matrix(1, 1), clip=title_area, alpha=False)
        if not page.get_text().strip():
            blank_indices.append(index)
            assert not page.get_drawings() and not page.get_images(), 'Alignment page is not blank'
        else:
            assert sum(1 for value in title.samples if value < 180) > 50, f'Invisible title glyphs on page {index + 1}'
        pixmap.save(output / f'page-{index + 1:02}.png')
        if index == 0:
            pixmap.save(output / 'cover.png')
        if 'Habit Tracker' in titles[-1]['title']:
            pixmap.save(output / 'monthly-checks.png')
        if 'Time Distribution' in titles[-1]['title'] and not (output / 'statistics.png').exists():
            pixmap.save(output / 'statistics.png')
        if titles[-1]['title'].startswith('2026-08-10') and '一日一页' in page.get_text():
            pixmap.save(output / 'daily-detail.png')
        if titles[-1]['title'].startswith('2026-08-03') and '一日一页' in page.get_text():
            pixmap.save(output / f'rich-log-{index + 1}.png')
    assert all(any(abs(span['size'] - size) < 0.01 for size in [7.5, 9, 12, 24, 64]) for span in spans), 'Unexpected print font size'
    assert all(span['size'] >= 8.99 or 'Weekly Timeline' in titles[span['page'] - 1]['title'] for span in spans), 'Compact type escaped weekly blocks'
    assert not issues, json.dumps(issues, ensure_ascii=False)
    assert calendar_pages and ('产品' in ''.join(calendar_pages) or '方案' in ''.join(calendar_pages)), 'Month grid contains no readable schedules'
    assert '月度回顾' in ''.join(calendar_pages) and '日子很长' in ''.join(calendar_pages), 'Month review/cite missing from eighth column'
    assert sticker_pages, 'No original sticker images in daily/annual pages'
    assert any('NotoSans' in span['font'] and '今日计划' in span['text'] for span in spans), 'Printed labels are not sans serif'
    assert any('WenKai' in span['font'] and '把这页书' in span['text'] for span in spans), 'User writing is not WenKai'
    # This explicit new paragraph must have a blank baseline above it, on the same page as the first paragraph.
    paragraph = next(span for span in spans if '把这页书' in span['text'])
    previous = [span for span in spans if span['page'] == paragraph['page'] and 'WenKai' in span['font'] and abs(span['bbox'][0] - paragraph['bbox'][0]) < 1 and span['bbox'][1] < paragraph['bbox'][1] and span['bbox'][1] > paragraph['bbox'][1] - 100]
    if previous:
        assert paragraph['bbox'][1] - max(span['bbox'][1] for span in previous) > paragraph['size'] * 2.5, 'Explicit paragraph spacing was flattened'
    else:
        # A paragraph starting in the next column already has a physical flow break.
        margin = 28 if 'a5' in source.stem else 40
        assert paragraph['bbox'][0] > margin + 25 or paragraph['page'] > 2, 'Paragraph separation was lost'
    assert timeline_pages
    for page in timeline_pages:
        right = '右页' in page.get_text()
        assert ('00:00' in page.get_text()) != right and ('24:00' in page.get_text()) != right, 'Hour axis repeated on right page or missing on left'
    populated = [page for page in timeline_pages if '2026-08-10 — 2026-08-16' in page.get_text()]
    assert 'MON' in ''.join(page.get_text() for page in populated) and 'SUN' in ''.join(page.get_text() for page in populated), 'Seven-day overview incomplete'
    assert sum(len([drawing for drawing in page.get_drawings() if drawing.get('fill')]) for page in populated) > 40, 'Populated timeline lacks colored activity blocks'
    assert '日志' in document[paragraph['page'] - 1].get_text(), 'Detailed notes are still in the weekly overview'
    assert 'Weekly Timeline' not in document[paragraph['page'] - 1].get_text().splitlines()[0], 'Log body in weekly overview'
    statistics = [page for page, title in zip(document, titles) if 'Time Distribution' in title['title']]
    stat_text = ''.join(page.get_text() for page in statistics)
    for label in ['标签', '领域', '待办', '关联时长']:
        assert label in stat_text, f'Missing distribution dimension: {label}'
    assert '关键字' not in stat_text and '二级标签' not in stat_text, 'Statistics are not nested or still contain keywords'
    assert sum(len([drawing for drawing in page.get_drawings() if drawing.get('fill')]) for page in statistics) > 20, 'Bar charts are missing'
    assert any(title['title'] == '2026 Time Distribution' for title in titles), 'Annual statistics missing'
    assert any(title['title'].startswith('2026-08-03') and 'Time Distribution' in title['title'] for title in titles), 'Weekly statistics missing'
    assert all('Do\n' not in page.get_text() and 'Complete\n' not in page.get_text() and 'Reaction' not in page.get_text() for page in document), 'Old badges/reaction headings remain'
    assert 'LumosTime' in document[0].get_text(), 'Cover wordmark missing'
    def has_color(pages, color):
        return any(drawing.get('fill') and all(abs(drawing['fill'][i] - color[i]) < 0.002 for i in range(3)) for page in pages for drawing in page.get_drawings())
    assert has_color(statistics, (0x52 / 255, 0x6b / 255, 0x5d / 255)), 'Statistics did not retain the user category color'
    assert has_color(populated, tuple(0.5 + 0.5 * value / 255 for value in [0x9a, 0x9d, 0xbd])), 'Weekly blocks did not retain the user activity color'
    if 'a5' in source.stem:
        for indices in [month_indices, timeline_indices]:
            assert len(indices) % 2 == 0
            for left, right in zip(indices[::2], indices[1::2]):
                assert (left + 1) % 2 == 0 and right == left + 1, 'Spread does not start on an even facing page'
        assert blank_indices, 'Cover/contents did not align spreads with a blank page'
    else:
        assert len(month_indices) == 1 and len(populated) == 1, 'A4 overview split across pages'
    # The complete month overview precedes its checklist, weeks and daily details.
    checklist = next(index for index, title in enumerate(titles) if 'Habit Tracker' in title['title'])
    first_day = next(index for index, title in enumerate(titles) if title['title'].startswith('2026-08-02'))
    assert max(month_indices) < checklist < timeline_indices[0] < first_day
    def save_spread(pages, name):
        images = []
        for page in pages:
            pix = page.get_pixmap(matrix=fitz.Matrix(1.5, 1.5), alpha=False)
            images.append(Image.frombytes('RGB', [pix.width, pix.height], pix.samples))
        spread = Image.new('RGB', (sum(image.width for image in images), max(image.height for image in images)), 'white')
        x = 0
        for image in images:
            spread.paste(image, (x, 0))
            x += image.width
        spread.save(output / name)
    save_spread(populated, 'weekly-timeline.png')
    save_spread([document[index] for index in month_indices], 'month-calendar.png')
    thumbs = []
    font = ImageFont.truetype('C:/Windows/Fonts/msyh.ttc', 15)
    for index in range(len(document)):
        with Image.open(output / f'page-{index + 1:02}.png') as image:
            image.thumbnail((290, 415))
            cell = Image.new('RGB', (310, 450), '#e8e8e4')
            cell.paste(image, ((310 - image.width) // 2, 22))
            ImageDraw.Draw(cell).text((12, 428), f'PAGE {index + 1}', font=font, fill='#303630')
            thumbs.append(cell)
    sheet = Image.new('RGB', (310 * 4, 450 * ((len(thumbs) + 3) // 4)), '#e8e8e4')
    for index, image in enumerate(thumbs):
        sheet.paste(image, ((index % 4) * 310, (index // 4) * 450))
    sheet.save(output / 'contact-sheet.jpg', quality=90)
    return {'file': str(source), 'pages': len(document), 'bytes': source.stat().st_size, 'titles': titles, 'contact': str(output / 'contact-sheet.jpg')}


if __name__ == '__main__':
    print(json.dumps([inspect(filename) for filename in sys.argv[1:]], ensure_ascii=False, indent=2))
